"""usage : python3 build_bjj.py <FCL_elliptic.sol> <FCL_babyjubjub.sol>
Generates FCL_babyjubjub.sol: FCL engine (joint 2+2 bit window, XYZZ, a=-3) on the short Weierstrass
curve isomorphic to BabyJubJub, with lazy reduction (254-bit field)."""
import re
import sys

import bjj

r, l = bjj.r, bjj.l
G = bjj.G
G2, G3 = bjj.w_mul(2, G), bjj.w_mul(3, G)
i2, i3 = pow(2, -1, l), pow(3, -1, l)
small = [(c, bjj.w_mul(c, G)) for c in [1, 2, 3, i2, 3 * i2 % l, i3, 2 * i3 % l]]
H = lambda v: "0x%064x" % v

DMAP = bytes([8, 12, 5, 6, 7, 9, 10, 11, 13, 14, 15]).hex().ljust(64, "0")

# halved doubling (U=Y), output -2P, inputs X<3p Y<=2p, outputs X<2p Y<2p
DBL = """{
    let M := mulmod(mulmod(add(X, sub(p, ZZ)), add(X, ZZ), p), _C3H, p)
    let V := mulmod(Y, Y, p)
    ZZZ := mulmod(mulmod(Y, V, p), ZZZ, p)
    ZZ := mulmod(V, ZZ, p)
    let S := mulmod(X, V, p)
    X := add(mulmod(M, M, p), mulmod(minus_2, S, p))
    Y := add(mulmod(V, V, p), mulmod(M, add(X, sub(p, S)), p))
}"""


def ADD(off):
    # accumulator = -A (negated Y), table entry E = (x, y) stored [-x, y, -y, x], output A+E, X<3p Y<2p
    return f"""let Pn := addmod(mulmod(mload(e), ZZ, p), X, p)
let R := add(mulmod(mload(add(e, {off})), ZZZ, p), Y)
switch Pn
case 0 {{
    switch ZZ
    case 0 {{
        X := mload(add(e, 0x60))
        Y := mload(add(e, {off}))
        ZZ := 1
        ZZZ := 1
    }}
    default {{
        switch mod(R, p)
        case 0 {{ X, Y, ZZ, ZZZ := dblNeg(X, Y, ZZ, ZZZ) }}
        default {{
            X := 0
            ZZ := 0
            ZZZ := 0
        }}
    }}
}}
default {{
    let PP := mulmod(Pn, Pn, p)
    Pn := mulmod(Pn, PP, p)
    ZZ := mulmod(ZZ, PP, p)
    ZZZ := mulmod(ZZZ, Pn, p)
    PP := mulmod(X, PP, p)
    X := add(add(mulmod(R, R, p), Pn), mulmod(minus_2, PP, p))
    Y := add(mulmod(R, add(X, sub(p, PP)), p), mulmod(Y, Pn, p))
}}"""


cases = "\n".join(
    f"""            case {H(P[0])} {{
                c := {H(c)}
                y := {H(P[1])}
            }}""" for c, P in small)

src = f'''//********************************************************************************************/
//  ___           _       ___               _         _    _ _
// | __| _ ___ __| |_    / __|_ _ _  _ _ __| |_ ___  | |  (_) |__
// | _| '_/ -_|_-< ' \\  | (__| '_| || | '_ \\  _/ _ \\ | |__| | '_ \\
// |_||_| \\___/__/_||_|  \\___|_|  \\_, | .__/\\__\\___/ |____|_|_.__/
//                                |__/|_|
///* Copyright (C) 2022 - Renaud Dubois - This file is part of FCL (Fresh CryptoLib) project
///* License: This software is licensed under MIT License
///* This Code may be reused including license and copyright notice.
///* See LICENSE file at the root folder of the project.
///* FILE: FCL_babyjubjub.sol
///*
///*
///* DESCRIPTION: BabyJubJub (circomlib) EdDSA verification. The twisted Edwards curve
///*  168700x^2+y^2=1+168696x^2y^2 over the BN254 scalar field is mapped, through its Montgomery
///*  form, to a short Weierstrass curve which is then rescaled (x,y)->(mu^2x,mu^3y) to a=-3
///*  (-3/a is a fourth power mod r). The FCL a=-3 XYZZ engine is then reused, with lazy
///*  reduction since the field is only 254 bits wide (values are kept below 4p between mulmods).
///*
//**************************************************************************************/
// SPDX-License-Identifier: MIT
pragma solidity >=0.8.19 <0.9.0;

library FCL_BabyJubJub {{
    // BN254 scalar field, base field of BabyJubJub
    uint256 constant p = {r};
    // order of the prime subgroup generated by Base8 (circomlib subOrder)
    uint256 constant n = {l};
    // short weierstrass coefficients of the isomorphic curve y^2 = x^3 - 3x + b
    uint256 constant a = {H(r - 3)};
    uint256 constant b = {H(bjj.b_iso)};
    // image of circomlib Base8
    uint256 constant gx = {H(G[0])};
    uint256 constant gy = {H(G[1])};
    uint256 constant minus_2 = {H(r - 2)};
    uint256 constant minus_2modn = {H(l - 2)};
    uint256 constant _2P = {H(2 * r)};
    // 3/2 mod p, halved doubling (U=Y instead of U=2Y)
    uint256 constant _C3H = {H(3 * pow(2, -1, r) % r)};
    uint256 constant _G2X = {H(G2[0])};
    uint256 constant _G2Y = {H(G2[1])};
    uint256 constant _G3X = {H(G3[0])};
    uint256 constant _G3Y = {H(G3[1])};
    // table index (i+4j) of the 11 points computed in XYZZ: 2Q,3Q,Q+G,Q+2G,Q+3G,2Q+G,..,3Q+3G
    uint256 constant _DMAP = 0x{DMAP};

    // circomlib twisted Edwards form and base point
    uint256 constant ED_A = 168700;
    uint256 constant ED_D = 168696;
    uint256 constant B8X = {bjj.B8[0]};
    uint256 constant B8Y = {bjj.B8[1]};
    // Edwards -> Weierstrass(a=-3): x = MU2*(1+y)/(1-y) + A3MU2, y = MU3*(1+y)/((1-y)x)
    uint256 constant MU2 = {H(bjj.MU2)};
    uint256 constant MU3 = {H(bjj.MU3)};
    uint256 constant A3MU2 = {H(bjj.A3MU2)};
    // inverses of MU2, MU3 (reverse map)
    uint256 constant IMU2 = {H(pow(bjj.MU2, -1, r))};
    uint256 constant IMU3 = {H(pow(bjj.MU3, -1, r))};

    /// @dev u^(p-2) mod p via the modexp precompile (0 -> 0)
    function pModInv(uint256 u) internal view returns (uint256 result) {{
        assembly ("memory-safe") {{
            let T := mload(0x40)
            mstore(T, 0x20)
            mstore(add(T, 0x20), 0x20)
            mstore(add(T, 0x40), 0x20)
            mstore(add(T, 0x60), u)
            mstore(add(T, 0x80), minus_2)
            mstore(add(T, 0xa0), p)
            if iszero(staticcall(gas(), 0x05, T, 0xc0, T, 0x20)) {{ revert(0, 0) }}
            result := mload(T)
        }}
    }}

    /// @dev twisted Edwards membership, coordinates must be reduced
    function ed_isOnCurve(uint256 x, uint256 y) internal pure returns (bool) {{
        if (x >= p || y >= p) return false;
        uint256 x2 = mulmod(x, x, p);
        uint256 y2 = mulmod(y, y, p);
        return addmod(mulmod(ED_A, x2, p), y2, p) == addmod(1, mulmod(ED_D, mulmod(x2, y2, p), p), p);
    }}

    /// @dev short Weierstrass (a=-3) membership
    function ecAff_isOnCurve(uint256 x, uint256 y) internal pure returns (bool) {{
        if (x >= p || y >= p) return false;
        return mulmod(y, y, p) == addmod(mulmod(addmod(mulmod(x, x, p), a, p), x, p), b, p);
    }}

    /// @dev Edwards affine -> Weierstrass affine. (0,1) (neutral) is mapped to (0,0)
    function ed2W(uint256 x, uint256 y) internal view returns (uint256 X, uint256 Y) {{
        if (x == 0) {{
            if (y == 1) return (0, 0);
            return (A3MU2, 0); // (0,-1), 2-torsion point
        }}
        uint256 om = addmod(1, p - y, p);
        uint256 inv = pModInv(mulmod(om, x, p)); // 1/((1-y)x)
        uint256 op = addmod(1, y, p);
        X = addmod(mulmod(MU2, mulmod(op, mulmod(inv, x, p), p), p), A3MU2, p);
        Y = mulmod(MU3, mulmod(op, inv, p), p);
    }}

    /// @dev Weierstrass affine -> Edwards affine. (0,0) is read as the neutral point
    function W2ed(uint256 X, uint256 Y) internal view returns (uint256 x, uint256 y) {{
        if (X == 0 && Y == 0) return (0, 1);
        if (Y == 0) return (0, p - 1);
        uint256 u = mulmod(addmod(X, p - A3MU2, p), IMU2, p);
        uint256 v = mulmod(Y, IMU3, p);
        // x = u/v, y = (u-1)/(u+1), one inversion
        uint256 up1 = addmod(u, 1, p);
        uint256 inv = pModInv(mulmod(v, up1, p));
        x = mulmod(mulmod(u, up1, p), inv, p);
        y = mulmod(mulmod(addmod(u, p - 1, p), v, p), inv, p);
    }}

    /**
     * @dev 8.A in Weierstrass affine coordinates, the key format of verifyRawW (precompute once per key).
     *      A must be on the Edwards curve. Returns (0,0) when 8A is the neutral point (small order key).
     */
    function pubKeyToW8(uint256 Ax, uint256 Ay) internal view returns (uint256 Wx, uint256 Wy) {{
        uint256 X = Ax;
        uint256 Y = Ay;
        uint256 Z = 1;
        assembly ("memory-safe") {{
            // three projective doublings, dbl-2008-bbjlp
            for {{ let i := 0 }} lt(i, 3) {{ i := add(i, 1) }} {{
                let B := mulmod(add(X, Y), add(X, Y), p)
                let C := mulmod(X, X, p)
                let D := mulmod(Y, Y, p)
                let E := mulmod(ED_A, C, p)
                let F := addmod(E, D, p)
                let J := addmod(F, sub(p, mulmod(2, mulmod(Z, Z, p), p)), p)
                X := mulmod(addmod(B, sub(_2P, add(C, D)), p), J, p)
                Y := mulmod(F, addmod(E, sub(p, D), p), p)
                Z := mulmod(F, J, p)
            }}
        }}
        if (X == 0) return (0, 0);
        uint256 zp = addmod(Z, Y, p);
        uint256 inv = pModInv(mulmod(addmod(Z, p - Y, p), X, p)); // 1/((Z-Y)X)
        Wx = addmod(mulmod(MU2, mulmod(mulmod(zp, X, p), inv, p), p), A3MU2, p); // mu^2 (Z+Y)/(Z-Y) + mu^2 A/3
        Wy = mulmod(MU3, mulmod(mulmod(zp, Z, p), inv, p), p); // mu^3 (Z+Y)Z/((Z-Y)X)
    }}

    /**
     * @dev Keys Q = +/-c.G with c in {{1, 2, 3, 1/2, 3/2, 1/3, 2/3}} (mod n) make some entries of the 2-bit joint
     *      window table degenerate, the multiplication is then rewritten as (u + c.v).G. Returns c, or 0.
     */
    function ecZZ_smallMultipleOfG(uint256 Q0, uint256 Q1) internal pure returns (uint256 c) {{
        assembly ("memory-safe") {{
            let y
            switch Q0
{cases}
            if c {{ if iszero(eq(Q1, y)) {{ c := sub(n, c) }} }}
        }}
    }}
'''

# core: taken from the P-256 engine (same structure), main loop with lazy reduction
p256 = open(sys.argv[1]).read()
i = p256.index("    /**\n     * @dev Core of uG+vQ")
j = p256.index("    /**\n     * @dev Computation of uG+vQ using Strauss-Shamir's trick, G basepoint, Q public key\n     *       Returns only x")
core = p256[i:j]
# replace the loop body by the lazy versions
k0 = core.index("            for {} lt(Q1, 256) { Q1 := sub(Q1, 4) } {")
loop = '''            for {} lt(Q1, 256) { Q1 := sub(Q1, 4) } {
                //@@DBL@@
                //@@DBL@@
                {
                    let e := or(and(shl(5, shr(Q1, scalar_u)), 0x180), and(shl(7, shr(Q1, scalar_v)), 0x600))
                    switch e
                    case 0 { Y := sub(_2P, Y) }
                    default {
                        e := add(Q0, e)
                        //@@ADD:0x40@@
                    }
                }
                //@@DBL@@
                //@@DBL@@
                {
                    let e := or(and(shl(7, shr(Q1, scalar_u)), 0x180), and(shl(9, shr(Q1, scalar_v)), 0x600))
                    switch e
                    case 0 { Y := sub(_2P, Y) }
                    default {
                        e := add(Q0, e)
                        //@@ADD:0x20@@
                    }
                }
            }
        }
    }

'''
core = core[:k0] + loop
core = core.replace("Returns the result in XYZZ coordinates (ZZ==0 iff point at infinity, then X==0).",
                    "Returns the result in XYZZ coordinates (ZZ==0 iff point at infinity, then X==0),\n     *      X < 3p and Y < 2p are not reduced (lazy reduction).")
out = []
for line in core.split("\n"):
    m = re.match(r"^(\s*)//@@(DBL|ADD:(0x\w+))@@\s*$", line)
    if m:
        body = DBL if m.group(2) == "DBL" else ADD(m.group(3))
        out += [m.group(1) + x for x in body.split("\n")]
    else:
        out.append(line)
src += "\n" + "\n".join(out)

src += '''    /**
     * @dev uG+vQ in Weierstrass affine coordinates, (0,0) for the point at infinity
     */
    function ecZZ_mulmuladd(uint256 Q0, uint256 Q1, uint256 scalar_u, uint256 scalar_v)
        internal
        view
        returns (uint256 X, uint256 Y)
    {
        uint256 ZZ;
        uint256 ZZZ;
        (X, Y, ZZ, ZZZ) = ecZZ_mulmuladd_core(Q0, Q1, scalar_u, scalar_v);
        ZZZ = pModInv(ZZZ);
        Y = mulmod(Y, ZZZ, p); //Y/zzz
        ZZ = mulmod(ZZ, ZZZ, p); //1/z
        X = mulmod(X, mulmod(ZZ, ZZ, p), p); //X/zz
    }

    /**
     * @dev Raw circomlib EdDSA check S.B8 == R8 + 8.hm.A, the challenge hm being already hashed
     *      (Poseidon, MiMC7, MiMCSponge or Pedersen in circomlib), the key given as W8 = pubKeyToW8(A).
     *      Same input checks as circomlibjs: R8 on curve, S < subOrder.
     *      No modular inversion besides the one of the table: R8 is compared in projective coordinates.
     */
    function verifyRawW(uint256 hm, uint256 R8x, uint256 R8y, uint256 S, uint256 Wx, uint256 Wy)
        internal
        view
        returns (bool ok)
    {
        if (S >= n || Wx >= p || Wy >= p || !ed_isOnCurve(R8x, R8y)) return false;
        // S.G - hm.(8A) = R8, result (X, Y, ZZ, ZZZ) stored in (Wx, Wy, hm, S)
        (Wx, Wy, hm, S) = ecZZ_mulmuladd_core(Wx, Wy, S, addmod(n - hm % n, 0, n));
        assembly ("memory-safe") {
            let om := addmod(1, sub(p, R8y), p) // 1-y
            switch om
            case 0 { ok := iszero(hm) } // R8 = (0,1), neutral: accept iff the result is the point at infinity
            default {
                let op := addmod(1, R8y, p) // 1+y
                // X/ZZ == (MU2(1+y) + A3MU2(1-y))/(1-y)
                let t := mulmod(addmod(mulmod(MU2, op, p), mulmod(A3MU2, om, p), p), hm, p)
                ok := and(iszero(iszero(hm)), eq(mulmod(Wx, om, p), t))
                // Y/ZZZ == MU3(1+y)/((1-y)x)
                t := mulmod(mulmod(MU3, op, p), S, p)
                ok := and(ok, eq(mulmod(mulmod(Wy, om, p), R8x, p), t))
            }
        }
    }

    /**
     * @dev Raw circomlib EdDSA check S.B8 == R8 + 8.hm.A with A in circomlib (Edwards) coordinates.
     *      Same input checks as circomlibjs verifyPoseidon/MiMC/Pedersen: A and R8 on curve, S < subOrder.
     */
    function verifyRaw(uint256 hm, uint256 R8x, uint256 R8y, uint256 S, uint256 Ax, uint256 Ay)
        internal
        view
        returns (bool)
    {
        if (!ed_isOnCurve(Ax, Ay)) return false;
        (uint256 Wx, uint256 Wy) = pubKeyToW8(Ax, Ay);
        return verifyRawW(hm, R8x, R8y, S, Wx, Wy);
    }
} //EOF
'''
open(sys.argv[2], "w").write(src)
print("ok", len(src.split(chr(10))), "lignes")
